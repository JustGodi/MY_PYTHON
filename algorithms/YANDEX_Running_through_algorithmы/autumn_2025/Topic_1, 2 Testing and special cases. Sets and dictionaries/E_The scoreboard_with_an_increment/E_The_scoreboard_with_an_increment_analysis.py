        # Каждую секунду к числу прибавляется его последняя цифра, определить значение числа через k секунд


def main():
    n, k = map(int, input().split()) # ввод данных

    while k > 0 and n % 2 != 0: # пока k (количество секунд) больше нуля и число нечётное
        n += n % 10 # к изначальному числу прибавить остаток от деления на 10 (т.е. послоеднюю цифру) 
        k -= 1 # количество секунд мину один

    if n % 10 == 0: # если последняя
        return n # вернуть число, тк при прибавлении нуля число не изменится
