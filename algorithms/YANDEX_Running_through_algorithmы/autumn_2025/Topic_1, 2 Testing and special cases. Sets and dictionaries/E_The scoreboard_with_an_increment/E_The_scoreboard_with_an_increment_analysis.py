        cycles = k // 4 # вычисляется количество циклов, т.к. у нас один цикл состоит из четырёх цифр то делим колличество секунд на 4
        n += (2 + 4 + 6 + 8) * cycles # прибавляем к числу n сумму одного цикла (2+4+6+8) умноженные на количество циклов
        k %= 4 # считается остаток от деления k (секнунд) на 4, это сколько секунд останется после расёта основныъ циклов
        for i in range(k): # из остатка от деления, задаём предел от колличества секнуд, и каждым шагом прибавляем последнюю цифр числа
            n += n % 10 # 
        return n # 
