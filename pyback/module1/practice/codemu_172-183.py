            # 175 Рандом в Python

        # Метод random модуля random (импортирован в шапке файла)

        # Метод random модуля random возвращает всевдослучайное число от 0.0 до 1.0. В параметр метода ничего не передаём. При каждом вызове метода будет возвращаться новое число
""" 
print(random.random())
 """

        # Метод randint модуля random

        # Метод randint модуля random возвращает псевдослучайное целое число из заданного диапазона. В первом параметре метода указываем начальное значение диапазона, во втором - его конечное значение
""" 
print(random.randint(0, 20))
print(random.randint(-15, -5))
print(random.randint(0, 0))
 """

        # Метод uniform модуля random

        # Метод uniform модуля random возвращает всевдослучайное вещественное число из заданного диапазона. В первом параметре метода указываем начальное значение диапазона, во втором - конечное значение
""" 
print(random.uniform(0, 10))
print(random.uniform(1, 2))
print(random.uniform(-1, -5))
 """

        # Метод randrange модуля random

        # Метод randrange модуля random возвращает случайное число из диапазона. В первом необязательном параметре метода указываем начало последовательности. Во втором обязательном параметре задаём конец. А в третьем необязательном параметре передаём шаг с которым будет выбираться число.
""" 
print(random.randrange(1, 10, 2))
print(random.randrange(11, 20))
print(random.randrange(30))
 """

        # Метод choice модуля random

        # Метод choice модуля random возвращает случайный элемент из последовательности(строки, списка, кортежа). В параметре метода указываем нужную нам последовательность
""" 
txt = 'abcde'
print(random.choice(txt))

lst = [1, 2, 3, 4, 5, 6]
print(random.choice(lst))

tpl = ('1', '2', '3', '4')
print(random.choice(tpl))
 """

        # Метод sample модуля random

        # Метод sample модуля random возвращает случайную выборку элементов из последовательности. В первом параметре метода указываем последовательность, во втором параметре - количество элементов, которые мы хотим выбрать случайнм образом

        # В третьем необязательном именнованном параметре k можем задать список элементов для повтора. Это позволяет повысить вероятность выборки заданных элементов. Обратите вниение что третий параметр метода добавлен только начиная с Python 3.9.
""" 
lst = [1, 2, 3, 4, 5, 6]
print(random.sample(lst, 3))

tpl = (1, 2, 3, 4, 5, 6)
print(random.sample(tpl, 3))

print(random.sample(range(1, 7), 3))

lst = [1, 2, 3]
print(random.sample(lst, 3, counts=[10, 2, 5]))
 """

        # Метод shuffle модуля random

        # Метод shuffle модуля random перемешивает порядок элементов в изменяемой последовательности. Поскольку кортеж является неизменяемой последовательностью, а элементы в множестве неупорядочены, выходит, что метод работает только со списком. После выполнения метода исходный список изменяется, а сам метод возвращает None. В параметре метода передаём нужный нам список
""" 
lst = [1, 2, 3, 4, 5, 6, 7, 8, 9]
print(lst)
random.shuffle(lst)
print(lst)
 """

        # Метод seed модуля random

        # Метод seed модуля random инициализирует или сохраняет случайное число. Для генерации случайных чисел метод использует текущее системное время ОС. Метод seed применяется до метода random. В необязательном параметре метода передаётся число для инициализации или своего рода маркировки сгенерированного числа. Поэтому при повторном применении метода random сгенерированное число не изменяется. Если же параметр оставить пустым, то будет генерироваться каждый раз новое число

random.seed(5)
print(random.random())
random.seed(5)
print(random.random())
random.seed(4)
print(random.random())
